def test_multi_tenant_cache_isolation():
    """
    Critical Multi-Tenant Isolation Invariant:
    A cached response generated by Tenant-Alpha must NEVER be delivered to Tenant-Beta!
    """
    reset_state()
    payload = {
        "model": "gpt-4o-mini",
        "messages": [{"role": "user", "content": "What is Python asyncio?"}]
    }

    # 1. Tenant Alpha requests -> MISS
    res_alpha_1 = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res_alpha_1.status_code == 200
    assert res_alpha_1.headers.get("x-gateway-cache-status") == "MISS"
    assert res_alpha_1.headers.get("x-gateway-tenant-id") == "tenant-alpha"

    # 2. Tenant Alpha repeats identical query -> L1 HIT
    res_alpha_2 = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res_alpha_2.status_code == 200
    assert res_alpha_2.headers.get("x-gateway-cache-status") == "HIT-L1_EXACT"

    # 3. Tenant Beta requests the exact same prompt -> MUST BE A MISS (Tenant Isolation)
    res_beta = client.post("/v1/chat/completions", json=payload, headers=BETA_HEADERS)
    assert res_beta.status_code == 200
    assert res_beta.headers.get("x-gateway-cache-status") == "MISS", "CRITICAL FLAW: Tenant Beta leaked Tenant Alpha's cache!"
    assert res_beta.headers.get("x-gateway-tenant-id") == "tenant-beta"
    print("[PASS] test_multi_tenant_cache_isolation")


