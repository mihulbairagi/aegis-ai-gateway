def test_cache_bypass_header():
    """Verify X-Bypass-Cache: true forces a fresh upstream call."""
    reset_state()
    payload = {
        "model": "gpt-4o-mini",
        "messages": [{"role": "user", "content": "Explain binary search"}]
    }
    # 1. First call -> MISS
    res1 = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res1.status_code == 200
    assert res1.headers.get("x-gateway-cache-status") == "MISS"

    # 2. Second call with bypass header -> MUST BE MISS
    bypass_headers = {**ALPHA_HEADERS, "X-Bypass-Cache": "true"}
    res2 = client.post("/v1/chat/completions", json=payload, headers=bypass_headers)
    assert res2.status_code == 200
    assert res2.headers.get("x-gateway-cache-status") == "MISS"
    print("[PASS] test_cache_bypass_header")


def test_rate_limiter_exceeded():
    """Verify rate limiter blocks burst traffic per tenant with 429."""
    reset_state()
    payload = {
        "model": "gpt-4o-mini",
        "messages": [{"role": "user", "content": "Burst ping"}]
    }
    # Drain bucket for tenant-alpha
    rate_limiter.buckets["tenant-alpha"] = (0.0, time.monotonic())

    res = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res.status_code == 429
    assert "Retry-After" in res.headers
    print("[PASS] test_rate_limiter_exceeded")


def test_circuit_breaker_auto_failover():
    """Verify circuit breaker trips to OPEN on 3 failures and routes to fallback."""
    reset_state()
    assert circuit_breaker.state == CircuitState.CLOSED

    for _ in range(3):
        circuit_breaker.record_failure()

    assert circuit_breaker.state == CircuitState.OPEN
    route, state = circuit_breaker.get_route()
    assert route == "fallback"
    assert state == CircuitState.OPEN
    print("[PASS] test_circuit_breaker_auto_failover")


