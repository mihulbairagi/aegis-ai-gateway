client = TestClient(app)

ALPHA_HEADERS = {"Authorization": "Bearer sk-aegis-tenant-alpha"}
BETA_HEADERS = {"Authorization": "Bearer sk-aegis-tenant-beta"}
ADMIN_HEADERS = {"X-Admin-Key": "admin-secret-key-12345"}

def reset_state():
    """Clear caches and state before each test."""
    semantic_cache.clear()
    rate_limiter.buckets.clear()
    circuit_breaker.state = CircuitState.CLOSED
    circuit_breaker.consecutive_failures = 0


def test_auth_and_unauthorized_rejection():
    """Verify missing or unknown API keys are rejected with 401."""
    reset_state()
    payload = {
        "model": "gpt-4o-mini",
        "messages": [{"role": "user", "content": "Hello"}]
    }
    
    # 1. No auth header -> 401
    res1 = client.post("/v1/chat/completions", json=payload)
    assert res1.status_code == 401
    assert "Invalid or missing" in res1.json()["detail"]

    # 2. Unknown / invalid key -> 401
    res2 = client.post("/v1/chat/completions", json=payload, headers={"Authorization": "Bearer fake-invalid-key"})
    assert res2.status_code == 401

    # 3. Valid tenant key -> 200
    res3 = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res3.status_code == 200
    print("[PASS] test_auth_and_unauthorized_rejection")


def test_admin_endpoint_protection():
    """Verify dangerous operations require ADMIN_API_KEY with 403 enforcement."""
    reset_state()
    
    # 1. Trip circuit without admin key -> 403 Forbidden
    res_unauth = client.post("/v1/gateway/circuit-breaker/trip")
    assert res_unauth.status_code == 403

    # 2. Trip circuit with admin key -> 200 OK
    res_trip = client.post("/v1/gateway/circuit-breaker/trip", headers=ADMIN_HEADERS)
    assert res_trip.status_code == 200
    assert circuit_breaker.state == CircuitState.OPEN

    # 3. Reset circuit without admin key -> 403
    assert client.post("/v1/gateway/circuit-breaker/reset").status_code == 403

    # 4. Reset circuit with admin key -> 200 OK
    res_reset = client.post("/v1/gateway/circuit-breaker/reset", headers=ADMIN_HEADERS)
    assert res_reset.status_code == 200
    assert circuit_breaker.state == CircuitState.CLOSED

    # 5. Flush cache with admin key -> 200 OK
    res_flush = client.delete("/v1/gateway/cache", headers=ADMIN_HEADERS)
    assert res_flush.status_code == 200
    print("[PASS] test_admin_endpoint_protection")


def test_multi_tenant_cache_isolation():
    """
    Critical Multi-Tenant Isolation Invariant:
    A cached response generated by Tenant-Alpha must NEVER be delivered to Tenant-Beta!
    """
    reset_state()
    payload = {
        "model": "gpt-4o-mini",
        "messages": [{"role": "user", "content": "What is Python asyncio?"}]
    }

    # 1. Tenant Alpha requests -> MISS
    res_alpha_1 = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res_alpha_1.status_code == 200
    assert res_alpha_1.headers.get("x-gateway-cache-status") == "MISS"
    assert res_alpha_1.headers.get("x-gateway-tenant-id") == "tenant-alpha"

    # 2. Tenant Alpha repeats identical query -> L1 HIT
    res_alpha_2 = client.post("/v1/chat/completions", json=payload, headers=ALPHA_HEADERS)
    assert res_alpha_2.status_code == 200
    assert res_alpha_2.headers.get("x-gateway-cache-status") == "HIT-L1_EXACT"

    # 3. Tenant Beta requests the exact same prompt -> MUST BE A MISS (Tenant Isolation)
    res_beta = client.post("/v1/chat/completions", json=payload, headers=BETA_HEADERS)
    assert res_beta.status_code == 200
    assert res_beta.headers.get("x-gateway-cache-status") == "MISS", "CRITICAL FLAW: Tenant Beta leaked Tenant Alpha's cache!"
    assert res_beta.headers.get("x-gateway-tenant-id") == "tenant-beta"
    print("[PASS] test_multi_tenant_cache_isolation")


